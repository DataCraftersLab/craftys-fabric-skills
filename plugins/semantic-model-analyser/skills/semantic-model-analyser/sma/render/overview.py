"""
The landing page's highlights: what stands out, a health checklist, and one data lineage
graph from source to measure. All of it is read off the dataset, as the cards are.

The lineage is table and query level, left to right: the connectors a query reaches,
the queries and tables they feed, and the tables each measure-host table's measures read.
Auto date/time tables collapse into one node, because forty of them drawn one by one is
the noise the graph exists to cut through.
"""

import re

AUTO_DATE = re.compile(r"^(LocalDateTable|DateTableTemplate)_[0-9a-f-]{36}$", re.I)
SOURCE_TIERS = ("connector", "inline")

#: Node tone by source kind. The page maps each to an accent token.
TONE = {"database": "db", "sharepoint": "file", "file": "file", "folder": "file",
        "web": "web", "odata": "web", "inline": "inline", "model": "model",
        "lakehouse": "model", "calculated": "calc", "measures": "measure"}


def is_auto_date(name):
    return bool(AUTO_DATE.match(name or ""))


def _short(target, n=34):
    t = (target or "").replace("https://", "").replace("http://", "")
    return t if len(t) <= n else t[:n - 1] + "…"


def _source_nodes(q):
    picked = [s for s in q.get("sources", []) if s.get("tier") in SOURCE_TIERS
              and s.get("functionName") != "Value.NativeQuery"]
    if not picked:
        picked = [s for s in q.get("sources", []) if s.get("tier") == "parser"][:1]
    out = []
    for s in picked:
        key = "src:%s|%s|%s" % (s.get("label"), s.get("target") or "", s.get("database") or "")
        label = s.get("label") or s.get("functionName") or "Source"
        if s.get("database"):
            label += " · " + s["database"]
        meta = _short(s.get("target")) or s.get("functionName") or ""
        out.append((key, label, meta, TONE.get(s.get("kind"), "other")))
    return out


def lineage(report):
    t = report.get("tmdl") or {}
    m = report.get("m") or {}
    tables = {tb["name"]: tb for tb in t.get("tables", [])}
    rel_tables = {x for r in t.get("relationships", []) for x in (r["fromTable"], r["toTable"])}
    nodes, edges, order = {}, set(), []

    def node(nid, **kw):
        if nid not in nodes:
            nodes[nid] = dict(id=nid, **kw)
            order.append(nid)
        return nid

    auto = [n for n in tables if is_auto_date(n)]
    if auto:
        node("auto", label="Auto date/time", meta="%d hidden tables" % len(auto), kind="table",
             tone="calc", hidden=True, flag="Generated by Auto date/time", obj=None)
        edges.add((node("src:dax", label="DAX (calculated)", meta="calculated tables",
                        kind="source", tone="calc", hidden=False, flag=None, obj=None), "auto"))

    def table_node(name):
        tb = tables[name]
        meta = []
        if tb.get("columns"):
            meta.append("%d columns" % tb["columns"])
        if tb.get("measures"):
            meta.append("%d measures" % tb["measures"])
        return node("t:" + name, label=name, meta=", ".join(meta) or "table", kind="table",
                    tone=None, hidden=bool(tb.get("isHidden")), flag=None, obj="t:" + name)

    query_of = {}
    for q in m.get("queries", []):
        name = q["name"]
        if is_auto_date(name):
            continue
        if name in tables:
            nid = table_node(name)
        else:
            meta = {"function": "function", "parameter": "parameter"}.get(q.get("kind"), "query")
            if q.get("loadEnabled") is False:
                meta += ", not loaded"
            nid = node("q:" + name, label=name, meta=meta, kind="query", tone=None,
                       hidden=q.get("loadEnabled") is False, flag=None, obj="q:" + name)
        query_of[name] = nid
        for key, label, meta, tone in _source_nodes(q):
            edges.add((node(key, label=label, meta=meta, kind="source", tone=tone,
                            hidden=False, flag=None, obj=None), nid))
    for q in m.get("queries", []):
        if q["name"] not in query_of:
            continue
        for d in q.get("dependsOn", []):
            if d in query_of:
                edges.add((query_of[d], query_of[q["name"]]))

    for name, tb in tables.items():
        if is_auto_date(name):
            continue
        nid = table_node(name)
        for p in tb.get("partitions", []):
            kind = p.get("kind")
            if kind == "calculated":
                edges.add((node("src:dax", label="DAX (calculated)", meta="calculated tables",
                                kind="source", tone="calc", hidden=False, flag=None, obj=None), nid))
            elif kind == "entity":
                expr = ((p.get("properties") or {}).get("expressionSource") or "").strip("'")
                if expr in query_of:
                    edges.add((query_of[expr], nid))
                else:
                    edges.add((node("src:lake", label="Direct Lake", meta="OneLake tables",
                                    kind="source", tone="model", hidden=False, flag=None,
                                    obj=None), nid))

    hosts = {}
    for ms in t.get("measures", []):
        hosts.setdefault(ms["table"], []).append(ms)
    for host, ms in sorted(hosts.items()):
        hid = node("m:" + host, label="Measures · " + host, meta="%d measures" % len(ms),
                   kind="measures", tone="measure", hidden=False, flag=None, obj=None)
        read = {x for one in ms for x in (one.get("tables") or [])}
        for tname in sorted(read):
            if tname in tables and not is_auto_date(tname):
                edges.add((table_node(tname), hid))

    # A measure table (measures, no columns) is drawn as its measures node only, and a
    # source left feeding nothing goes with it.
    for name, tb in tables.items():
        nid = "t:" + name
        if nid in nodes and tb.get("measures") and not tb.get("columns"):
            del nodes[nid]
            order.remove(nid)
            edges = {e for e in edges if nid not in e}
    feeding = {a for a, _ in edges}
    for nid in [i for i in order if nodes[i]["kind"] == "source" and i not in feeding]:
        del nodes[nid]
        order.remove(nid)

    # A table nothing in the model uses: no query, measure or relationship reads it. It
    # may still sit on a report visual, which the definition does not show.
    outgoing = {a for a, _ in edges}
    for nid in order:
        n = nodes[nid]
        if n["kind"] == "table" and nid.startswith("t:"):
            name = nid[2:]
            if (nid not in outgoing and name not in rel_tables and not tables[name].get("measures")
                    and not tables[name].get("isCalculationGroup")):
                n["flag"] = "Nothing in the model uses it"
        if n["kind"] == "query" and n["hidden"] and nid not in outgoing:
            n["flag"] = "Not loaded, and nothing reads it"

    for n in nodes.values():
        if n["tone"] is None:
            ups = [a for a, b in edges if b == n["id"]]
            tones = {nodes[a]["tone"] for a in ups if nodes[a]["tone"]}
            if len(tones) > 1:
                tones.discard("other")
            n["tone"] = tones.pop() if len(tones) == 1 else ("mix" if tones else "other")
    # Two passes, so a table fed by a query takes the tone that query just took.
    for n in nodes.values():
        if n["kind"] in ("table", "query") and n["tone"] == "other":
            ups = {nodes[a]["tone"] for a, b in edges if b == n["id"]} - {"other"}
            if ups:
                n["tone"] = ups.pop() if len(ups) == 1 else "mix"

    return {"nodes": [nodes[i] for i in order], "edges": sorted(edges),
            "autoDate": len(auto)}


MEASURE_CAP = 150


def measure_lineage(report, cap=MEASURE_CAP):
    """Tables to measures to the measures built on them, left to right.

    Measures take their display folder's accent, as in the chain explorer. Past `cap`
    measures the graph keeps the most-read ones and everything they depend on, and says
    how many it shows; the chain explorer reaches the rest one at a time.
    """
    t = report.get("tmdl") or {}
    meas = t.get("measures") or []
    if not meas:
        return None
    by = {m["name"]: m for m in meas}
    shown = meas
    if len(meas) > cap:
        keep = set()
        for m in sorted(meas, key=lambda m: (-len(m.get("usedBy") or []), m["name"].lower())):
            if len(keep) >= cap:
                break
            stack = [m["name"]]
            while stack:
                x = stack.pop()
                if x in keep or x not in by:
                    continue
                keep.add(x)
                stack.extend(by[x].get("dependsOn") or [])
        shown = [m for m in meas if m["name"] in keep]
    names = {m["name"] for m in shown}

    folders = sorted({m.get("folder") or "Other" for m in shown}, key=lambda f: (f == "Other", f.lower()))
    tone = {}
    for i, f in enumerate(x for x in folders if x != "Other"):
        tone[f] = "f%d" % (i % 8)
    tone["Other"] = "other"

    nodes, edges, order = {}, set(), []
    for m in shown:
        nid = "m:" + m["name"]
        folder = m.get("folder") or "Other"
        meta = [] if folder == "Other" else [folder]
        if m.get("usedBy"):
            meta.append("read by %d" % len(m["usedBy"]))
        nodes[nid] = dict(id=nid, label=m["name"], meta=" · ".join(meta) or "measure",
                          kind="measure", tone=tone[folder], hidden=bool(m.get("isHidden")),
                          flag=None, obj=nid)
        order.append(nid)
        for d in m.get("dependsOn") or []:
            if d in names:
                edges.add(("m:" + d, nid))
        for tb in m.get("tables") or []:
            if is_auto_date(tb):
                continue
            tid = "t:" + tb
            if tid not in nodes:
                nodes[tid] = dict(id=tid, label=tb, meta="table", kind="table", tone="table",
                                  hidden=False, flag=None, obj=tid)
                order.insert(0, tid)
            edges.add((tid, nid))
    legend = [(tone[f], f) for f in folders if f != "Other"][:8]
    if "Other" in folders:
        legend.append(("other", "No folder"))
    return {"nodes": [nodes[i] for i in order], "edges": sorted(edges),
            "total": len(meas), "shown": len(shown), "legend": legend}


def flagged(graph):
    return [n for n in graph["nodes"] if n.get("flag") and n["id"] != "auto"]


# --------------------------------------------------------------- highlights

def highlights(report, pages, graph):
    """What stands out, most pressing first. Each is (tone, value, text, sub, href)."""
    t = report.get("tmdl") or {}
    m = report.get("m") or {}
    out = []
    file_t = pages.get("tmdl", {}).get("file")
    file_q = pages.get("pq", {}).get("file")

    if t:
        n_tab = len(t.get("tables", []))
        auto = graph.get("autoDate", 0)
        if auto:
            rels = sum(1 for r in t.get("relationships", [])
                       if is_auto_date(r["fromTable"]) or is_auto_date(r["toTable"]))
            out.append((0, "bad", auto, "of %d tables are auto date/time tables" % n_tab,
                        "Power BI generated them, with %d of the %d relationships. One shared "
                        "Date table replaces them." % (rels, len(t.get("relationships", []))),
                        "%s#t-rel" % file_t))

    fs = (t.get("findings") or []) + (m.get("findings") or [])
    act = [f for f in fs if f["level"] in ("error", "warning")]
    if act:
        codes = {}
        for f in act:
            codes[f["code"]] = codes.get(f["code"], 0) + 1
        top = sorted(codes.items(), key=lambda kv: -kv[1])[:2]
        out.append((1, "warn", len(act), "findings worth acting on",
                    "Most often: " + ", ".join("%s (%d)" % (c, n) for c, n in top) + ".",
                    "%s#t-findings" % file_t if file_t else "%s#q-audit" % file_q))
    elif fs:
        out.append((6, "good", 0, "findings worth acting on",
                    "%d notes worth knowing, none that call for a change." % len(fs),
                    "%s#t-findings" % file_t if file_t else "%s#q-audit" % file_q))

    if t:
        st = t.get("relationshipStats") or {}
        rels = [r for r in t.get("relationships", [])
                if not (is_auto_date(r["fromTable"]) or is_auto_date(r["toTable"]))]
        odd = st.get("bidirectional", 0) + st.get("manyToMany", 0)
        by_name = {tb["name"]: tb for tb in t.get("tables", [])}
        # A measure table or a calculation group stands alone by design.
        disc = [x for x in (st.get("tablesDisconnected") or []) if not is_auto_date(x)
                and not (by_name.get(x, {}).get("measures") and not by_name.get(x, {}).get("columns"))
                and not by_name.get(x, {}).get("isCalculationGroup")]
        if not rels and len(t.get("tables", [])) > 1:
            out.append((1, "bad", 0, "relationships between the model's own tables",
                        "Every table stands alone; the joins happen before the model, if at all.",
                        "%s#t-rel" % file_t))
        elif odd or disc:
            bits = []
            if st.get("bidirectional"):
                bits.append("%d both-direction" % st["bidirectional"])
            if st.get("manyToMany"):
                bits.append("%d many-to-many" % st["manyToMany"])
            if disc:
                bits.append("%d table%s unconnected" % (len(disc), "" if len(disc) == 1 else "s"))
            out.append((3, "warn", len(rels), "relationships", ", ".join(bits).capitalize() + ".",
                        "%s#t-rel" % file_t))
        elif rels:
            out.append((7, "good", len(rels), "relationships",
                        "All single-direction, every table connected.", "%s#t-rel" % file_t))

        ai = t.get("aiReadiness")
        if ai and "ai" in pages:
            sm = ai["summary"]
            ratio = sm["passed"] / max(1, sm["total"])
            tone = "good" if ratio >= 0.8 else ("warn" if ratio >= 0.5 else "bad")
            out.append((2 if tone != "good" else 5, tone, "%d/%d" % (sm["passed"], sm["total"]),
                        "AI readiness checks pass",
                        "What Copilot and data agents find when they read this model.",
                        pages["ai"]["file"]))

        meas = t.get("measures", [])
        if meas:
            desc = sum(1 for x in meas if (x.get("description") or "").strip())
            pct = round(100 * desc / len(meas))
            tone = "good" if pct >= 80 else ("warn" if pct >= 40 else "bad")
            out.append((4 if tone != "good" else 8, tone, "%d%%" % pct, "of measures are described",
                        "%d of %d carry a description." % (desc, len(meas)),
                        "%s#card-t5" % file_t))

    if m.get("queries"):
        qs = m["queries"]
        # Entered data has no source to fold to, so its "barrier" is not one.
        stepped = [q for q in qs if q.get("steps") and q.get("sourceKind") != "inline"]
        barriers = sum(1 for q in stepped if q.get("foldBreakStep"))
        conns = {(s.get("label"), s.get("target"), s.get("database")) for q in qs
                 for s in q.get("sources", []) if s.get("tier") == "connector"}
        tone = "warn" if barriers else "good"
        out.append((4 if barriers else 9, tone, len(conns),
                    "data source%s behind %d queries" % ("" if len(conns) == 1 else "s", len(qs)),
                    "%d with a potential folding barrier." % barriers if barriers
                    else "No folding barrier detected.", "%s#q-structural" % file_q))

    gone = flagged(graph)
    if gone:
        out.append((3, "warn", len(gone), "tables or queries nothing in the model uses",
                    "Flagged in the lineage below. A report visual may still use them.",
                    "#lineage"))

    out.sort(key=lambda x: x[0])
    return [o[1:] for o in out[:4]]


# ---------------------------------------------------------------- checklist

def checklist(report, tmdl_checks, m_checks, graph):
    """Every scorecard row on one list: (group, label, value, total, status)."""
    rows = []

    def add(group, label, v, tot, thr):
        if not tot:
            return
        ratio = v / tot
        status = "pass" if ratio >= thr else ("warn" if ratio >= thr * 0.6 else "fail")
        rows.append((group, label, v, tot, status))

    t = report.get("tmdl") or {}
    if t:
        n_tab = len(t.get("tables", []))
        add("Semantic model", "Tables that are not auto date/time",
            n_tab - graph.get("autoDate", 0), n_tab, 1.0)
        st = t.get("relationshipStats") or {}
        n_rel = len(t.get("relationships", []))
        add("Semantic model", "Relationships single-direction, not many-to-many",
            n_rel - st.get("bidirectional", 0) - st.get("manyToMany", 0), n_rel, 1.0)
        for label, v, tot, thr in tmdl_checks:
            add("Semantic model", label, v, tot, thr)
    for label, v, tot, thr in m_checks:
        add("Power Query", label, v, tot, thr)
    ai = t.get("aiReadiness") if t else None
    if ai:
        for g in ai["groups"]:
            known = [c for c in g["checks"] if c["status"] != "na"]
            add("AI readiness", g["title"], sum(1 for c in known if c["status"] == "pass"),
                len(known), 1.0)
    return rows
